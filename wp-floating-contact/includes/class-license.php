    // ─── Trial API ────────────────────────────────────────────────────────────

    /**
     * Records the trial start timestamp the very first time this runs.
     * Safe to call on every page load — does nothing if already started.
     */
    public static function maybe_start_trial(): void {
        if ( ! get_option( self::TRIAL_OPTION ) ) {
            update_option( self::TRIAL_OPTION, time(), false );
        }
    }

    /** True if the 14-day trial window is still open. */
    public static function is_trial_active(): bool {
        $start = (int) get_option( self::TRIAL_OPTION, 0 );
        if ( ! $start ) {
            return false;
        }
        return ( time() - $start ) < ( self::TRIAL_DAYS * DAY_IN_SECONDS );
    }

    /** How many full days remain in the trial (0 when expired). */
    public static function trial_days_remaining(): int {
        $start = (int) get_option( self::TRIAL_OPTION, 0 );
        if ( ! $start ) {
            return 0;
        }
        $elapsed = ( time() - $start ) / DAY_IN_SECONDS;
        return (int) max( 0, ceil( self::TRIAL_DAYS - $elapsed ) );
    }

    /** True once the trial period has ended (and no valid license). */
    public static function trial_expired(): bool {
        $start = (int) get_option( self::TRIAL_OPTION, 0 );
        if ( ! $start ) {
            return false; // trial never even started
        }
        return ( time() - $start ) >= ( self::TRIAL_DAYS * DAY_IN_SECONDS );
    }

    /**
     * Master gate: plugin features are available if either condition holds.
     * Called from the main plugin file to decide whether to load Frontend/Tracker.
     */
    public static function can_use(): bool {
        return self::is_active() || self::is_trial_active();
    }

    // ─── License API ──────────────────────────────────────────────────────────

    /**
     * Returns true if a valid serial has been activated on this site.
     */
    public static function is_active(): bool {
        $stored = get_option( self::OPTION_KEY, '' );
        if ( empty( $stored ) ) {
            return false;
        }
        return in_array( $stored, self::$valid_hashes, true );
    }

    /**
     * Attempts to activate the plugin with the given serial number.
     * Input is upper-cased and trimmed before hashing so formatting differences
     * (spaces, lowercase) are tolerated.
     *
     * @param string $serial  Raw user input.
     * @return bool           True on success, false if serial is invalid.
     */
    public static function activate( string $serial ): bool {
        $clean = strtoupper( trim( $serial ) );
        // Normalise dash/hyphen variants to standard ASCII hyphen.
        $clean = preg_replace( '/[\x{2010}-\x{2015}\x{2212}]/u', '-', $clean );
        $hash  = hash( 'sha256', $clean );

        if ( in_array( $hash, self::$valid_hashes, true ) ) {
            update_option( self::OPTION_KEY, $hash );
            return true;
        }
        return false;
    }

    /**
     * Removes the stored license hash, deactivating the plugin.
     */
    public static function deactivate(): void {
        delete_option( self::OPTION_KEY );
    }

    /**
     * Returns a masked representation of the activated serial for display
     * (e.g. "WPFC-••••••-••••••-S67AQZ").
     * We only know the hash, so we derive the suffix from the first 6 hex chars
     * of the stored hash — purely decorative.
     */
    public static function get_masked_display(): string {
        $hash = get_option( self::OPTION_KEY, '' );
        if ( empty( $hash ) ) {
            return '';
        }
        return 'WPFC-••••••-••••••-' . strtoupper( substr( $hash, 0, 6 ) );
    }
